class GenerateSeparableState(object):
    def __init__(self, name='sep_train_set', size=10000, sub_dim=2, space_number=3, mix_number=10):
        self.name = name
        self.size = size
        self.sub_dim = sub_dim
        self.space_number = space_number
        self.mix_number = mix_number  # Used to control the number of component states mixed in each separable state
        self.dataset = []

    def generate_sub_state(self):
        # Generate a random matrix that follows a normal distribution.
        # The first parameter 0 is the mean (mean) of the normal distribution, i.e., the expected value.
        # The second parameter 1, is the standard deviation of the normal distribution, which controls
        # the dispersion of the distribution.
        # The third parameter [self.sub_dim, self.sub_dim] is the dimension of the generated random matrix.
        q1 = np.random.normal(0, 1, [self.sub_dim, self.sub_dim])
        q2 = np.random.normal(0, 1, [self.sub_dim, self.sub_dim])
        q = q1 + 1j * q2  # A complex matrix q is created by combining the real part q1 with the imaginary part q2
        q = np.matrix(q)  # Create a random Complex matrix H. Convert an array or list to a NumPy matrix object.
        q = (q + q.H) / 2  # Generate GUE
        q = np.dot(q, q.H) / np.trace(np.dot(q, q.H))  # Make it positive, and normalize to unity.
        # np.dot(q, q.H)) computes the product of the matrix q with its conjugate transpose, resulting in a Hermite
        # matrix. np.trace(np.dot(q, q.H)) computes the trace of the product of the matrix q with its conjugate
        # transpose. Each of its elements is divided by the trace of the product of the matrix q and its conjugate
        # transpose, which makes the trace of the matrix 1, i.e. normalizes the matrix
        return q

    def generate(self):
        for _ in range(int(self.size / self.mix_number)):
            state = []  # Used to store the component states generated by each loop
            for _ in range(self.mix_number):
                # s = 0
                if self.space_number > 1:
                    s = self.generate_sub_state()
                    for _ in range(self.space_number - 1):
                        s = np.reshape(np.kron(s, self.generate_sub_state()),
                                       [s.shape[0] * self.sub_dim, s.shape[1] * self.sub_dim])
                        # Use the np.einsum function to compute the tensor product between component states and then
                        # morph the result into a matrix
                    state.append(s)
            for j in range(self.mix_number):
                weight = np.random.random(j + 1)
                weight /= np.sum(weight)
                # Generate random weights and normalize them to ensure that all weights sum to 1
                # mix = np.zeros([self.sub_dim ** self.space_number, self.sub_dim ** self.space_number])
                mix = np.zeros([self.sub_dim ** self.space_number, self.sub_dim ** self.space_number], dtype=complex)
                # Initialize an all-zero matrix mix to store the separable states after mixing
                # The following loop then accumulates over the first j + 1 component states
                for k in range(j + 1):
                    mix += weight[k] * state[k]  # Accumulate over the first j + 1 component states
                self.dataset.append((mix, 0))  # Assign label 0 for separable states
        # print((np.array(self.dataset[0][0])).shape)


class GenerateTwoSeparableState(object):
    def __init__(self, name='two_sep_train_set', size=10000, sub_dim=2, space_number=3, mix_number=10):
        self.name = name
        self.size = size
        self.sub_dim = sub_dim
        self.space_number = space_number
        self.mix_number = mix_number  # Used to control the number of component states mixed in each separable state
        self.dataset = []

    def generate_sub_state(self):
        # Generate a random matrix that follows a normal distribution.
        q1 = np.random.normal(0, 1, [self.sub_dim, self.sub_dim])
        q2 = np.random.normal(0, 1, [self.sub_dim, self.sub_dim])
        q = q1 + 1j * q2  # Complex matrix creation
        q = np.matrix(q)  # Convert to matrix
        q = (q + q.H) / 2  # Generate GUE
        q = np.dot(q, q.H) / np.trace(np.dot(q, q.H))  # Make it positive and normalize to unity
        return q

    def generate(self):
        for _ in range(int(self.size / self.mix_number)):
            state = []  # Store the component states generated by each loop
            for _ in range(self.mix_number):
                # s = 0
                if self.space_number > 1:
                    s = self.generate_sub_state()
                    for _ in range(self.space_number - 1):
                        db_q1 = np.random.normal(0, 1, [4, 4])
                        db_q2 = np.random.normal(0, 1, [4, 4])
                        db_s = db_q1 + 1j * db_q2
                        s = np.reshape(np.kron(db_s, self.generate_sub_state()),
                                       [pow(self.sub_dim, self.space_number), pow(self.sub_dim, self.space_number)])
                    state.append(s)
            for j in range(self.mix_number):
                weight = np.random.random(j + 1)
                weight /= np.sum(weight)  # Generate random weights and normalize them
                mix = np.zeros([self.sub_dim ** self.space_number, self.sub_dim ** self.space_number], dtype=complex)
                # Initialize an all-zero matrix to store the separable states after mixing
                for k in range(j + 1):
                    mix += weight[k] * state[k]  # Accumulate over the first j + 1 component states
                if self.limit_constraints(mix):
                    self.dataset.append((mix, 1))  # Assign label 1 for two-separable states

    @staticmethod
    def limit_constraints(mix):
        rho_11 = mix[0, 0]
        rho_22 = mix[1, 1]
        rho_33 = mix[2, 2]
        rho_44 = mix[3, 3]
        rho_55 = mix[4, 4]
        rho_66 = mix[5, 5]
        rho_77 = mix[6, 6]
        rho_88 = mix[7, 7]
        rho_12 = mix[0, 1]
        rho_25 = mix[1, 4]
        rho_35 = mix[2, 4]

        if abs(rho_12) > np.sqrt(rho_11 * rho_44):
            return True
        elif abs(rho_25) > np.sqrt(rho_11 * rho_66):
            return True
        elif abs(rho_35) > np.sqrt(rho_11 * rho_77):
            return True
        elif abs(rho_88) > np.sqrt(rho_22 * rho_77):
            return True
        elif abs(rho_88) > np.sqrt(rho_33 * rho_66):
            return True
        elif abs(rho_88) > np.sqrt(rho_44 * rho_55):
            return True
        else:
            return False


class GenerateEntangledState(object):
    def __init__(self, name='entangled_train_set', size=10000, sub_dim=2, space_number=3, mix_number=10):
        self.name = name
        self.size = size
        self.sub_dim = sub_dim
